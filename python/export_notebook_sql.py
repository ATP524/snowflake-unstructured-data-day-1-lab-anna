"""Export a notebook's SQL cells, in order, to a .sql file.

sql/08.extract_reports.ipynb is the single source of step 08. Run this to get a
plain .sql copy (for a worksheet, code review, or a scheduled task). The copy is
generated: edit the notebook, not the copy.

    python python/export_notebook_sql.py                         # 08 -> build/08.extract_reports.sql
    python python/export_notebook_sql.py <notebook.ipynb> [out.sql]
"""
import sys
from pathlib import Path

from sql_runner import find_project_root, notebook_sql_text

DEFAULT_NOTEBOOK = "sql/08.extract_reports.ipynb"


def export_notebook_sql(notebook, output=None):
    root = find_project_root(Path(__file__).parent)
    notebook = Path(notebook)
    if not notebook.is_absolute():
        notebook = root / notebook
    output = Path(output) if output else root / "build" / (notebook.stem + ".sql")
    header = (
        f"-- GENERATED from {notebook.relative_to(root)} by python/export_notebook_sql.py.\n"
        "-- Do not edit this file; edit the notebook and export again.\n\n"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header + notebook_sql_text(notebook))
    return output


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    notebook = argv[0] if argv else DEFAULT_NOTEBOOK
    output = argv[1] if len(argv) > 1 else None
    print(f"Wrote {export_notebook_sql(notebook, output)}")


if __name__ == "__main__":
    main()
